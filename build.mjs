import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Bundle local CommonJS modules; Obsidian is supplied by the host app.
const root = path.dirname(fileURLToPath(import.meta.url));
const modules = new Map();
async function collect(name) {
    if (modules.has(name)) return;
    const source = await readFile(path.join(root, 'src', name + '.js'), 'utf8');
    modules.set(name, source);
    for (const match of source.matchAll(/require\(['"]\.\/([^'"]+)['"]\)/g)) await collect(match[1]);
}
await collect('main');
const entries = [...modules].map(([name, source]) => `${JSON.stringify(name)}: function(module, exports, require) {\n${source}\n}`).join(',\n');
await writeFile(path.join(root, 'main.js'), `// Generated by npm run build. Edit src/ instead.\nconst __modules = {\n${entries}\n};\nconst __cache = {};\nfunction __load(name) {\n if (!__cache[name]) {\n  const module = { exports: {} }; __cache[name] = module;\n  __modules[name](module, module.exports, id => id.startsWith('./') ? __load(id.slice(2)) : require(id));\n }\n return __cache[name].exports;\n}\nmodule.exports = __load('main');\n`);
